/* Builds src/knowledge-index.js: the passages the "Ask me" chat searches.
   Run with `npm run knowledge` (also runs before dev and build).
   Sources, in addition to the hand-written entries in src/knowledge.js:
   - knowledge/*.md: split into one passage per "## " section (long sections are split further)
   - knowledge/interview/answered.md: one passage per question + answer
   - knowledge/interview/to-review.md: only questions where "My answer:" has been filled in
   - src/roles.js and src/projects-data.js: one passage per role and per project
   The generated file is committed, so the Vercel function never depends on the build order. */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { resolve, relative, basename } from 'node:path';
import { roles, roleUrl } from '../src/roles.js';
import { projects } from '../src/projects-data.js';

const root = resolve(import.meta.dirname, '..');
const kdir = resolve(root, 'knowledge');

// Where a passage from each knowledge file links to on the site.
const URLS = {
  'profile.md': '/#about', 'experience.md': '/resume.html', 'projects.md': '/#resume', 'ai.md': '/#projects',
  'skills.md': '/#toolbox', 'education-languages.md': '/resume.html', 'references.md': '/#resume',
  'ways-of-working.md': '/resume.html', 'interview/answered.md': '/chat.html', 'interview/to-review.md': '/chat.html',
};
const MAX = 1100; // characters per passage before splitting

const clean = (s) => s.replace(/\*\*/g, '').replace(/`/g, '').replace(/\n{3,}/g, '\n\n').trim();
const slug = (s) => s.toLowerCase().normalize('NFKD').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 48);

function files(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = resolve(dir, f);
    return statSync(p).isDirectory() ? files(p) : f.endsWith('.md') ? [p] : [];
  });
}

function splitLong(text) {
  if (text.length <= MAX) return [text];
  const out = []; let cur = '';
  for (const para of text.split(/\n(?=- |\*\*|\d+\. |\n)/)) {
    if (cur && (cur + '\n' + para).length > MAX) { out.push(cur.trim()); cur = ''; }
    cur += (cur ? '\n' : '') + para;
  }
  if (cur.trim()) out.push(cur.trim());
  return out;
}

const docs = [];
const add = (d) => docs.push({ ...d, text: clean(d.text), tags: d.tags || '' });

for (const path of files(kdir)) {
  const rel = relative(kdir, path).replace(/\\/g, '/');
  if (rel === 'README.md') continue;
  const md = readFileSync(path, 'utf8');
  const url = URLS[rel] || '/';

  if (rel === 'interview/answered.md' || rel === 'interview/to-review.md') {
    const prefix = rel.endsWith('answered.md') ? 'A' : 'R';
    let section = '';
    const re = new RegExp(String.raw`^## (.+)$|^\*\*${prefix}(\d+)\.\s*(?:[🔴🟡⚪]\s*)?(.+?)\*\*\s*\n([\s\S]*?)(?=^\*\*${prefix}\d+\.|^---|^## |(?![\s\S]))`, 'gmu');
    for (const m of md.matchAll(re)) {
      if (m[1]) { section = m[1].replace(/^\d+\.\s*/, ''); continue; }
      const [, , n, q, body] = m;
      let answer = body.trim();
      if (prefix === 'R') {
        const a = body.match(/- My answer:\s*([\s\S]*)$/);
        answer = a ? a[1].trim() : '';
        if (!answer) continue; // unanswered review questions are not knowledge yet
      }
      add({ id: `${prefix.toLowerCase()}${n}`, title: q.trim(), url, tags: `interview question ${section}`, text: answer });
    }
    continue;
  }

  const fileTitle = (md.match(/^# (.+)$/m) || [, basename(rel, '.md')])[1];
  const parts = md.split(/^## /m);
  const intro = parts.shift().replace(/^# .+$/m, '').trim();
  const sections = [...(intro ? [[fileTitle, intro]] : []), ...parts.map((p) => {
    const nl = p.indexOf('\n');
    return [`${fileTitle}: ${p.slice(0, nl).trim()}`, p.slice(nl + 1).trim()];
  })];
  for (const [title, body] of sections) {
    splitLong(body).forEach((text, i) => add({ id: `${slug(rel)}-${slug(title)}${i ? '-' + i : ''}`, title, url, tags: fileTitle, text }));
  }
}

for (const r of roles) {
  const text = [
    `${r.title} at ${r.org}, ${r.dates}${r.type ? ` (${r.type})` : ''}.`, r.summary,
    ...(r.did || []).map((d) => '- ' + d),
    r.showcase?.intro, r.showcase?.appNote,
    r.team?.intro, r.team?.members?.length ? 'Team: ' + r.team.members.map((m) => `${m.name} (${m.role}${m.badge ? ', ' + m.badge : ''})`).join(', ') + '.' : '',
    r.learned ? 'What I learned: ' + r.learned : '',
  ].filter(Boolean).join('\n');
  add({ id: `role-${r.id}`, title: `${r.short}: ${r.title}`, url: roleUrl(r.id), tags: `experience role job ${r.short} ${r.org} ${(r.tags || []).join(' ')}`, text });
}

for (const p of projects) {
  add({ id: `project-${slug(p.title)}`, title: p.title, url: p.link || '/#work', tags: `project built ${p.status} ${p.when || ''} ${(p.tech || []).join(' ')}`, text: `${p.title} (${p.status}, ${p.when || ''}): ${p.text}` });
}

const out = `/* GENERATED by scripts/build-knowledge.mjs: do not edit by hand.
   Edit knowledge/*.md, src/roles.js or src/projects-data.js, then run \`npm run knowledge\`. */
export const docs = ${JSON.stringify(docs, null, 1)};
`;
writeFileSync(resolve(root, 'src/knowledge-index.js'), out);
console.log(`knowledge: ${docs.length} passages → src/knowledge-index.js`);
